#include "table.h"
#include "taylor.h"
#include <stdio.h>

int main(void) {
  // Границы отрезка для 6 варианта
  const double a = 0.0;
  const double b = 1.0;

  printf("========================================================\n");
  printf("   Вариант 6: f(x) = sh(x) на отрезке [%.1f, %.1f]\n", a, b);
  printf("   Ряд: x + x^3/3! + ... + x^(2n-1)/(2n-1)!\n");
  printf("========================================================\n\n");

  // 1. Определение машинного эпсилон
  double eps = get_machine_eps();
  printf("Машинное эпсилон (eps) для типа double: %e\n\n", eps);

  // 2. Ввод количества частей разбиения отрезка
  int n = 0;
  printf("Введите число равных частей разбиения n (например, 10): ");
  if (scanf("%d", &n) != 1 || n <= 0) {
    printf("Ошибка: n должно быть целым положительным числом!\n");
    return 1;
  }

  // 3. Ввод экспериментального коэффициента k
  double k = 0.0;
  printf("Введите коэффициент k для точности eps*k (например, 10 или 100): ");
  if (scanf("%lf", &k), k <= 1.0) {
    printf("Ошибка: k должно быть положительным вещественным числом!\n");
    return 1;
  }

  printf("\nЗаданная точность вычислений (eps * k): %e\n", eps * k);

  // 4. Построение и вывод таблицы
  print_table(a, b, n, eps, k);

  return 0;
}
